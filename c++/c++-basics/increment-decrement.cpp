// Increment and Decrement

#include <iostream>
using namespace std;

int main() {

    // pre increment ++x
    // post increment x++
    // pre decrement --x
    // post decrement x--
    // i += 1 or i++

    int i = 5;
    i++; // x becomes 6

    // int x = 5, y;
    // y = ++x --> y = 6 and x = 6 --> first increment the value then assign it to y

    // post increment
    ++i; // x becomes 7
    // int x = 5, y;
    // y = x++; --> y = 5, x = 5 --> use the variable then increment


    return 0;
}

